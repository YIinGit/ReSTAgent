"""生成演示/回归用的示例稿（故意包含多种典型错误）。"""
from __future__ import annotations

import pathlib

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

OUT = pathlib.Path(__file__).resolve().parent.parent / "samples" / "示例稿_待审.docx"

TITLE = "为什么天空是蓝色的？"
SUBTITLE = "从瑞利散射到人眼的错觉"

P1 = ('抬头看天，很多人会问："为什么天空是蓝色的？"。这个问题看似简单，答案却牵扯到光学、'
      '大气物理与视觉生理三个层面。我们在本篇中会仔细的分析这一现象，并说明一些常见的误解。')

P2 = ("首先，太阳光本身并不是单一颜色的光，而是包含各种波长的连续光谱,其中紫光的波长最短,"
      "红光的波长最长。当阳光进入大气层后，会与空气分子发生散射。根据瑞利散射理论，"
      "散射强度与波长的平方成正比，因此波长越短的光被散射得越厉害。")

P3 = ("那么，既然紫光散射最强，为什么我们看到的不是紫色天空呢？原因有两方面：其一是太阳辐射中"
      "紫光的能量本来就比蓝光少；其二是人眼对紫光的敏感度较低，而对蓝光更敏感。那么，综合这两个"
      "因素，天空在我们眼中就呈现出蓝色。那么，这是否意味着傍晚的天空也应该是蓝色的呢？"
      "显然不是。那么，傍晚的光到底去了哪里？这就要引入另一个概念--大气消光。")

P4 = ("当太阳接近地平线时，阳光需要穿过更厚的大气层。以海平面为标准，太阳在天顶时穿过的大气质量"
      "约为 1，而在地平线附近可达到 38 左右。这意味这光程变长了，短波光在途中被大量散射掉，"
      "剩下较多的长波光进入我们的眼睛，于是天空与太阳都呈现出橙红色。")

P5 = ("到这里，我们解释了天空为什么是蓝色的、夕阳为什么是红色的。但是，云为什么是白色的？"
      "云中的水滴直径通常在 10 微米到 20 微米之间,远大于可见光波长,此时起主导作用的是米氏散射，"
      "各种波长的光被近似等比例地散射，所以云呈现白色。而雨后的彩虹则又是另一回事：折射、"
      "反射与色散共同作用的结果。")

P6 = ("值得强调的是，天空的颜色还与观测地点的高度有关。在海拔３０００米的高原，天空往往呈现出"
      "更深的蓝色，因为空气稀薄、散射粒子减少。有观测记录显示，在海拔 5000 米处，天顶的亮度"
      "只有海平面的三分之一左右。此外，其它因素如气溶胶、水汽、火山灰、等都会影响天空的颜色。")

P7 = ("最后，我们来做一个小结。天空之所以是蓝色的，是因为瑞利散射使短波光在大气中大量散射，"
      "而人眼的敏感度又进一步放大了这一效果；夕阳之所以是红色的，是因为光程变长、短波光被散射殆尽。"
      "理解了这一点，你就能明白为什么高原的天空更蓝、为什么火星的天空是粉红色——那里的尘埃"
      "让米氏散射占了上风。。。")

P8 = ("当然，这个解释仍然是一种近似。真实的大气是一个复杂的散射介质，包含分子、气溶胶与云滴等多种"
      "成分，每一类成分的散射相函数都不相同。如果读者有兴趣，可以进一步查阅大气辐射传输方面的教材，"
      "例如《大气物理学》中关于散射的章节。需要说明的是，本文为了叙述方便，省略了偏振与多次散射的讨论，"
      "这些内容在专业教材中会有更严格的推导。")

P9 = ('（本文数据参考公开气象资料，如有出入请以原始文献为准。另外，文中的"米氏散射"一词在不同'
      '教材中译名略有差异，此处采用较常见的一种。）')


def main():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "宋体"
    style.font.size = Pt(10.5)

    h = doc.add_heading(TITLE, level=1)
    h.alignment = WD_ALIGN_PARAGRAPH.LEFT
    doc.add_paragraph(SUBTITLE)
    doc.add_paragraph("作者：示例作者　｜　板块：物理")

    doc.add_heading("一、太阳光与散射", level=2)
    for t in (P1, P2, P3):
        doc.add_paragraph(t)

    doc.add_heading("二、夕阳与云", level=2)
    for t in (P4, P5, P6):
        doc.add_paragraph(t)

    doc.add_heading("三、小结", level=2)
    for t in (P7, P8, P9):
        doc.add_paragraph(t)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
